// Helper functions
export const getCategoryByKey = (key) => {
  return MENU_DATA[key];
};

export const getSubcategoryByKey = (mainKey, subKey) => {
  const mainCategory = MENU_DATA[mainKey];
  if (!mainCategory) return null;
  
  // Tìm trong categories
  let subcategory = mainCategory.categories?.find(cat => cat.key === subKey);
  if (subcategory) return { ...subcategory, type: 'category', parent: mainCategory };
  
  // Tìm trong subcategories của mỗi category
  if (mainCategory.categories) {
    for (const cat of mainCategory.categories) {
      if (cat.subcategories) {
        const found = cat.subcategories.find(sub => sub.key === subKey);
        if (found) return { ...found, type: 'subcategory', parent: cat, mainParent: mainCategory };
      }
    }
  }
  
  // Tìm trong featured (deprecated - giữ để backward compatibility)
  subcategory = mainCategory.featured?.find(feat => feat.key === subKey);
  if (subcategory) return { ...subcategory, type: 'featured', parent: mainCategory };
  
  return null;
};

export const getAllCategories = () => {
  return Object.values(MENU_DATA);
};

export const getAllSubcategories = () => {
  const allSubs = [];
  Object.values(MENU_DATA).forEach(mainCat => {
    if (mainCat.categories) {
      mainCat.categories.forEach(cat => {
        allSubs.push({
          ...cat,
          type: 'category',
          parent: mainCat
        });
        // Thêm subcategories nếu có
        if (cat.subcategories) {
          cat.subcategories.forEach(sub => {
            allSubs.push({
              ...sub,
              type: 'subcategory',
              parent: cat,
              mainParent: mainCat
            });
          });
        }
      });
    }
    if (mainCat.featured) {
      mainCat.featured.forEach(feat => {
        allSubs.push({
          ...feat,
          type: 'featured', 
          parent: mainCat
        });
      });
    }
  });
  return allSubs;
};

// Lấy tất cả subcategories của một category
export const getSubcategoriesByCategoryKey = (categoryKey) => {
  for (const mainCat of Object.values(MENU_DATA)) {
    if (mainCat.categories) {
      const category = mainCat.categories.find(cat => cat.key === categoryKey);
      if (category && category.subcategories) {
        return category.subcategories;
      }
    }
  }
  return [];
};